#!/usr/bin/env node
/**
 * Snapshot the portfolio content for the chatbot.
 *
 * `src/data/profile.ts` is the single source of truth for the site. Kobi runs
 * on the backend, which can't import from the frontend bundle, so this script
 * transpiles that file and writes a plain data module the backend compiles.
 * Run automatically before `backend:build`; commit the result.
 *
 *   node scripts/sync-chat-profile.js
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const ts = require("typescript");

const SRC = path.resolve(__dirname, "../src/data/profile.ts");
const OUT = path.resolve(__dirname, "../backend/src/data/siteProfile.ts");

const { outputText } = ts.transpileModule(fs.readFileSync(SRC, "utf8"), {
  compilerOptions: {
    module: ts.ModuleKind.CommonJS,
    target: ts.ScriptTarget.ES2020,
  },
});
const sandbox = { exports: {}, module: { exports: {} } };
vm.runInNewContext(outputText, sandbox);
const profile = sandbox.exports.PROFILE;
if (!profile || !Array.isArray(profile.projects)) {
  console.error("sync-chat-profile: PROFILE not found in src/data/profile.ts");
  process.exit(1);
}

const banner = `/**
 * GENERATED by scripts/sync-chat-profile.js from src/data/profile.ts — do not edit.
 * Change the content in src/data/profile.ts, then run \`npm run sync:chat\`.
 */
`;
fs.writeFileSync(
  OUT,
  `${banner}\nexport const siteProfile = ${JSON.stringify(profile, null, 2)};\n`,
);
console.log(
  `✓ chat profile synced: ${profile.projects.length} projects, ${profile.experiences.length} experiences`,
);
